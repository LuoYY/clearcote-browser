"""Regenerate sdk/testdata/humanize_scroll_vectors.json from the Python planners (SC 232 lane E).

usage: python tests/gen_scroll_vectors.py   (from sdk/python)

Pins the wheel anchor, the hand drift between wheel events, the trackpad swipe stream, the drag-start
hesitation, the scroll-into-view distance and the input-device choice across Python (_scroll.py,
_motion.drag_hesitation), Node (scroll.ts, motion.ts dragHesitation) and .NET (Scroll.cs,
Motion.DragHesitation). Before 0.52 the anchor numbers differed in all three SDKs."""

import json
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from clearcote import _scroll as S  # noqa: E402
from clearcote._motion import drag_hesitation, hesitate_then_drag, make_persona, mulberry32  # noqa: E402

OUT = os.path.join(os.path.dirname(__file__), "..", "..", "testdata", "humanize_scroll_vectors.json")


def _samples(seq):
    n = len(seq)
    idx = sorted({0, n // 4, n // 2, (3 * n) // 4, n - 1}) if n else []
    return [[i, seq[i][0], seq[i][1], seq[i][2]] for i in idx]


def main():
    anchor = []
    for k, (vw, vh) in enumerate([(1280, 800), (1920, 1080), (1366, 768), (390, 844), (1180, 760)]):
        for r in range(4):
            seed = 100 + 10 * k + r
            x, y = S.anchor_point(vw, vh, mulberry32(seed))
            anchor.append({"vw": vw, "vh": vh, "rng": seed, "x": x, "y": y})
    drift = []
    for seed in range(1, 9):
        dx, dy = S.wheel_drift(mulberry32(seed))
        drift.append({"rng": seed, "dx": dx, "dy": dy})
    # the trackpad identity (R2): report rate + inertia decay per persona, then streams on those traits
    trackpad_traits = []
    for pid in ["ha-1", "ha-2", "ha-3", "ha-4", "ha-5", "ha-6", "user-7423", "lane-e"]:
        t = S.trackpad_traits(make_persona(pid).seed)
        trackpad_traits.append({"persona": pid, "hz": t.hz, "decay_ms": t.decay_ms})
    trackpad = []
    for k, (pid, dx, dy) in enumerate([("ha-1", 0, 30), ("ha-2", 0, 120), ("ha-3", 0, 400), ("ha-4", 0, -650),
                                       ("ha-5", 0, 2400), ("ha-6", 300, 0), ("user-7423", 90, 160)]):
        seed = 200 + k
        ev = S.plan_trackpad(dx, dy, S.trackpad_traits(make_persona(pid).seed), mulberry32(seed))
        trackpad.append({"persona": pid, "dx": dx, "dy": dy, "rng": seed, "n": len(ev), "samples": _samples(ev)})
    hesitation = []
    for k, (pid, frm, to, dur) in enumerate([
        ("ha-1", (100, 200), (600, 240), None), ("ha-2", (400, 300), (120, 300), None),
        ("ha-3", (50, 50), (50, 450), 180.0), ("ha-4", (300, 300), (300.5, 300.2), None),
        ("ha-5", (640, 400), (900, 120), 360.0), ("user-7423", (10, 10), (500, 600), 90.0),
    ]):
        steps = drag_hesitation(frm, to, make_persona(pid), mulberry32(300 + k), dur)
        hesitation.append({"persona": pid, "from": list(frm), "to": list(to), "rng": 300 + k, "dur_ms": dur,
                           "n": len(steps), "samples": _samples(steps)})
    held = []
    for k, (pid, frm, to, w, settle) in enumerate([
        ("ha-1", (100, 200), (600, 240), 220.0, True), ("ha-3", (400, 300), (128, 300), 130.0, False),
        ("ha-6", (50, 50), (50, 450), 300.0, True), ("user-7423", (640, 400), (900, 120), 90.0, False),
    ]):
        steps, nc = hesitate_then_drag(frm, to, make_persona(pid), w, settle, mulberry32(400 + k))
        held.append({"persona": pid, "from": list(frm), "to": list(to), "rng": 400 + k, "window_ms": w,
                     "settle": settle, "n": len(steps), "creep": nc, "samples": _samples(steps)})
    need = []
    view = (0.0, 0.0, 1280.0, 800.0)
    for box, frac in [({"x": 500, "y": 3000, "width": 160, "height": 40}, 0.4),
                      ({"x": 500, "y": -900, "width": 160, "height": 40}, 0.3),
                      ({"x": 1500, "y": 100, "width": 100, "height": 40}, 0.5),
                      ({"x": 10, "y": 900, "width": 300, "height": 1200}, 0.5),
                      ({"x": 10, "y": 300, "width": 300, "height": 40}, 0.5)]:
        dx, dy = S.scroll_need(box, view, frac)
        need.append({"box": box, "view": list(view), "frac": frac, "dx": dx, "dy": dy})
    device = []
    for plat, opt in [("macos", None), ("windows", None), ("linux", None), ("android", None), (None, None),
                      ("macos", "mouse"), ("windows", "trackpad"), ("linux", "Touchpad"), ("macos", "")]:
        device.append({"platform": plat, "option": opt, "device": S.input_device(plat, opt)})
    doc = {
        "_about": ("Shared vectors for the humanize wheel + drag-start planners (SC 232 lane E): _scroll.py / "
                   "scroll.ts / Scroll.cs anchor_point, wheel_drift, trackpad_traits (persona), plan_trackpad (on the "
                   "persona's trackpad traits), scroll_need, input_device and _motion.drag_hesitation / dragHesitation / "
                   "DragHesitation must give these from makePersona(persona).seed and mulberry32(rng) (abs tolerance "
                   "1e-6). Generated by sdk/python/tests/gen_scroll_vectors.py."),
        "anchor": anchor, "drift": drift, "trackpad_traits": trackpad_traits, "trackpad": trackpad,
        "hesitation": hesitation, "held": held, "need": need, "device": device,
    }
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        json.dump(doc, f, indent=1)
        f.write("\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
