"""Regenerate sdk/testdata/humanize_typing_vectors.json from the Python keyboard planner (_keys.py).

usage: python tests/gen_typing_vectors.py   (from sdk/python)

The Node (test/keys.test.ts) and .NET (KeysTests.cs) suites read the same file, so a planner change in
one SDK that is not made in the others fails there. Regenerate only together with the matching change
in all three planners (keys.ts, Keys.cs). The persona_pin block pins make_persona's existing fields:
it must NOT change when the typing planner does (the typing identity is a salted side stream)."""

import dataclasses
import json
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from clearcote._keys import (  # noqa: E402
    bigram_class, finger_of, flight_ms, modifier_lag_ms, modifier_lead_ms, plan_gap, plan_repeat, split_chord,
    submit_pause_ms, tab_pause_ms, typing_traits,
)
from clearcote._motion import make_persona, mulberry32  # noqa: E402

OUT = os.path.join(os.path.dirname(__file__), "..", "..", "testdata", "humanize_typing_vectors.json")

PERSONAS = ["ha-1", "ha-2", "ha-3", "ha-4", "ha-5", "ha-6", "user-7423", "forms-unit", "t"]
PIN_SEEDS = ["ha-1", "ha-2", "ha-3", "ha-4", "ha-5", "ha-6", 0, 1, 12345, "abc"]
CHARS = "aqzAQZ1!`=-]\\'/.,;pPlmn hjkfdsgt\n\tö5%"
PAIRS = ["ed", "de", "ju", "ki", "en", "th", "he", "ce", "un", "fr", "aa", "a ", " a", "zq", "p;", "ab", "AE", "ö1",
         "rt", "nm", "my", "lo"]
CHORDS = ["a", "Enter", "Control+a", "ControlOrMeta+a", "Control+Shift+ArrowLeft", "Shift++", "+", "Shift",
          "Alt+Shift+Meta+F4", "Control+Backspace"]
GAP_TEXTS = [
    ("ha-1", 11, "the quick brown fox, jumps over. lazy dogs"),
    ("ha-2", 12, "decided junk kiwi ennui; thrown"),
    ("ha-3", 13, "Hello World! 42 times?"),
    ("user-7423", 14, "minimum unnumbered ceded"),
]
KS_PERSONA, KS_RNG = "ks-1", 99
KS_WORDS = ("the quick brown fox jumps over the lazy dog, and then it runs back. a search box takes what "
            "people type: short words, some longer ones, numbers like 42 and 1999. ")


def ks_text(n=501):
    t = ""
    while len(t) < n:
        t += KS_WORDS
    return t[:n]


def pid(seed):
    return seed if isinstance(seed, str) else seed


def main():
    pin = []
    for seed in PIN_SEEDS:
        pin.append({"input": seed, "persona": dataclasses.asdict(make_persona(seed))})
    traits = []
    for p in PERSONAS:
        t = typing_traits(make_persona(p).seed)
        traits.append({"persona": p, **dataclasses.asdict(t)})
    fingers = [{"ch": c, "want": list(finger_of(c)) if finger_of(c) else None} for c in CHARS]
    bigrams = []
    for pr in PAIRS:
        cls, jump = bigram_class(pr[0], pr[1])
        bigrams.append({"prev": pr[0], "ch": pr[1], "cls": cls, "jump": jump})
    gaps = []
    for p, rs, text in GAP_TEXTS:
        tr = typing_traits(make_persona(p).seed)
        rng = mulberry32(rs)
        flights = [flight_ms(tr, text[i], text[i + 1], rng) for i in range(len(text) - 1)]
        rng = mulberry32(rs)
        full = [plan_gap(tr, text[i], text[i + 1], rng) for i in range(len(text) - 1)]
        gaps.append({"persona": p, "rng": rs, "text": text, "flight_ms": flights, "gap_ms": full})
    chords = [{"key": k, "mods": split_chord(k)[0], "key_out": split_chord(k)[1]} for k in CHORDS]
    timing = []
    for p, rs in (("ha-1", 21), ("ha-4", 22), ("user-7423", 23)):
        tr = typing_traits(make_persona(p).seed)
        rng = mulberry32(rs)
        rp = plan_repeat(tr, rng)
        timing.append({"persona": p, "rng": rs,
                       "repeat": [rp.first_ms, rp.gap_ms, rp.release_ms],
                       "lead": modifier_lead_ms(rng), "lag": modifier_lag_ms(rng),
                       "submit": [submit_pause_ms(tr, rng) for _ in range(4)],
                       "tab": [tab_pause_ms(tr, rng) for _ in range(4)]})
    kt = ks_text()
    tr = typing_traits(make_persona(KS_PERSONA).seed)
    rng = mulberry32(KS_RNG)
    ks = [plan_gap(tr, kt[i], kt[i + 1], rng) for i in range(len(kt) - 1)]
    doc = {
        "_about": ("Shared vectors for the humanize keyboard planner: sdk/python/clearcote/_keys.py, "
                   "sdk/node/src/keys.ts and sdk/dotnet/src/Clearcote/Keys.cs must give these exact answers "
                   "(abs tolerance 1e-9 ms) from makePersona(persona).seed and mulberry32(rng). persona_pin pins "
                   "make_persona's EXISTING fields (unchanged by the typing identity, a salted side stream). "
                   "ks_reference: 500 planned gaps (persona ks_persona, mulberry32(ks_rng), ks_text) that the "
                   "humanized typing of each SDK must match in distribution (two-sample KS). Generated by "
                   "sdk/python/tests/gen_typing_vectors.py."),
        "persona_pin": pin,
        "typing_traits": traits,
        "finger_of": fingers,
        "bigram_class": bigrams,
        "gaps": gaps,
        "split_chord": chords,
        "timing": timing,
        "ks_persona": KS_PERSONA,
        "ks_rng": KS_RNG,
        "ks_text": kt,
        "ks_reference": ks,
    }
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        json.dump(doc, f, indent=1, ensure_ascii=False)
        f.write("\n")
    print("wrote", os.path.normpath(OUT))


if __name__ == "__main__":
    main()
