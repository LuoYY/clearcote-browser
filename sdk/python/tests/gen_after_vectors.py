"""Regenerate sdk/testdata/humanize_after_vectors.json from the Python planners (SC 232 lane C).

usage: python tests/gen_after_vectors.py   (from sdk/python)

Pins plan_ambient, the after-action traits / dwell / move-off planners and the attention model's read
pause across the three SDKs: the Node (test/after-action.test.ts) and .NET (AfterActionTests.cs) suites read
the same file. Regenerate only together with the matching change in all three planners."""

import json
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from clearcote._attention import explore_notches, idle_drifts, read_pause_ms  # noqa: E402
from clearcote._motion import (  # noqa: E402
    after_rng, after_traits, dwell_ms, make_persona, move_off_delay_ms, move_off_roll, mulberry32, plan_ambient,
    plan_dwell, plan_move_off,
)

OUT = os.path.join(os.path.dirname(__file__), "..", "..", "testdata", "humanize_after_vectors.json")
PERSONAS = ["ha-1", "ha-2", "ha-3", "ha-4", "ha-5", "ha-6", "user-7423"]


def pick(steps):
    n = len(steps)
    idx = sorted({0, n // 4, n // 2, (3 * n) // 4, n - 1})
    return {"n": n, "total_ms": sum(s[2] for s in steps),
            "samples": [[i, steps[i][0], steps[i][1], steps[i][2]] for i in idx]}


def build():
    traits = []
    for pid in PERSONAS:
        t = after_traits(make_persona(pid))
        traits.append({"persona": pid, "dwell_ms": t.dwell_ms, "move_off_rate": t.move_off_rate,
                       "move_off_delay_ms": t.move_off_delay_ms, "read_tempo": t.read_tempo})
    ambient = []
    for pid, seed, frm, vp, ms in [("ha-1", 1, (300, 200), (1280, 800), 1200), ("ha-2", 2, (900, 600), (1280, 720), 450),
                                   ("ha-3", 3, (50, 50), (1920, 1080), 2500), ("user-7423", 4, (640, 400), (800, 600), 300)]:
        st = plan_ambient(frm, {"width": vp[0], "height": vp[1]}, make_persona(pid), ms, mulberry32(seed))
        ambient.append({"persona": pid, "rng": seed, "from": list(frm), "viewport": list(vp), "ms": ms, **pick(st)})
    dwell = []
    for pid, seed, at, box, ms in [("ha-1", 5, (460, 320), (400, 300, 120, 40), 400),
                                   ("ha-4", 6, (101, 101), (100, 100, 4, 4), 900),
                                   ("ha-6", 7, (500, 500), None, 150)]:
        b = None if box is None else {"x": box[0], "y": box[1], "width": box[2], "height": box[3]}
        st = plan_dwell(at, b, make_persona(pid), ms, mulberry32(seed))
        dwell.append({"persona": pid, "rng": seed, "at": list(at), "box": list(box) if box else None, "ms": ms, **pick(st)})
    # Per persona: the after-action stream walked as the humanizer walks it (dwell length, then 40 click
    # rolls with their delays and move-off targets, then the attention draws).
    streams = []
    for pid in PERSONAS:
        p = make_persona(pid)
        r = after_rng(p)
        d = dwell_ms(p, r)
        hits, rolls, delays, targets = 0, [], [], []
        for i in range(40):
            hit = move_off_roll(p, r, hits, i)
            rolls.append(1 if hit else 0)
            if hit:
                hits += 1
                delays.append(move_off_delay_ms(p, r))
                targets.append(list(plan_move_off((200 + (i * 137) % 800, 150 + (i * 89) % 600),
                                                  {"width": 1280, "height": 800}, p, r)))
        reads = [read_pause_ms(n, p, r) for n in (0, 120, 3000, 20000, 50000)]
        notches = [explore_notches(r) for _ in range(10)]
        idle = [idle_drifts(g, r) for g in (1.0, 1.6, 5.0)]
        streams.append({"persona": pid, "dwell_ms": d, "rolls": rolls, "delays": delays, "targets": targets,
                        "reads": reads, "notches": notches, "idle": idle})
    doc = {
        "_about": ("Shared vectors for the after-action planners (SC 232 lane C): sdk/python/clearcote/_motion.py "
                   "plan_ambient / after_traits / after_rng / dwell_ms / plan_dwell / move_off_roll / move_off_delay_ms / "
                   "plan_move_off and _attention.py read_pause_ms / explore_notches / idle_drifts; sdk/node/src/motion.ts + "
                   "attention.ts and sdk/dotnet/src/Clearcote/Motion.cs + Attention.cs must give these exact values "
                   "(abs tolerance 1e-6). Generated by sdk/python/tests/gen_after_vectors.py."),
        "after_traits": traits, "ambient": ambient, "dwell": dwell, "streams": streams,
    }
    return doc


def main():
    doc = build()
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        json.dump(doc, f, indent=1)
        f.write("\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
