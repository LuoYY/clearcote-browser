def main():
    traits = []
    for pid in PERSONAS:
        t = shape_traits(make_persona(pid))
        traits.append({"persona": pid, "overshoot_rate": t.overshoot_rate, "curve": t.curve,
                       "drag_tempo": t.drag_tempo})
    paths = []
    found = {}
    for pid, seed, frm, to, w, mode in CASES:
        steps = plan_move(frm, to, make_persona(pid), target_w=w, settle=mode == "settle",
                          held=mode == "held", rng=mulberry32(seed))
        n = len(steps)
        idx = sorted({0, n // 4, n // 2, (3 * n) // 4, n - 1})
        paths.append({"persona": pid, "rng": seed, "from": list(frm), "to": list(to), "target_w": w,
                      "mode": mode, "n": n, "total_ms": sum(s[2] for s in steps),
                      "samples": [[i, steps[i][0], steps[i][1], steps[i][2]] for i in idx]})
        found[mode] = found.get(mode, 0) + 1
    doc = {
        "_about": ("Shared vectors for the humanize path planner: sdk/python/clearcote/_motion.py plan_move/"
                   "plan_drag/shape_traits, sdk/node/src/motion.ts and sdk/dotnet/src/Clearcote/Motion.cs must "
                   "plan these exact paths (abs tolerance 1e-6 px / ms; shape traits 1e-12) from "
                   "makePersona(persona) and mulberry32(rng). Generated by sdk/python/tests/gen_motion_vectors.py. "
                   "Randomness rule (SC 232 PLAN.md): the seed fixes persona TRAITS only; every per-action draw pinned "
                   "here (paths, drags, ambient, timings, wheel_anchor points) is drawn from the explicit mulberry32(rng) "
                   "a test passes, never from the persona seed. The SDKs keep per-action draws unseeded at run time."),
        "shape_traits": traits,
        "paths": paths,
        **sc232_sections(),
    }
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        json.dump(doc, f, indent=1)
        f.write("\n")
    print("wrote", OUT, found)


