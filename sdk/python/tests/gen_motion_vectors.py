"""Regenerate sdk/testdata/humanize_motion_vectors.json from the Python planner.

usage: python tests/gen_motion_vectors.py   (from sdk/python)

The Node (test/motion-shape.test.ts) and .NET (MotionShapeTests.cs) suites read the same file, so a
planner change in one SDK that is not made in the others fails there. Regenerate only together with
the matching change in all three planners."""

import json
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from clearcote._motion import make_persona, mulberry32, plan_move, shape_traits  # noqa: E402

OUT = os.path.join(os.path.dirname(__file__), "..", "..", "testdata", "humanize_motion_vectors.json")

PERSONAS = ["ha-1", "ha-2", "ha-3", "ha-4", "ha-5", "ha-6", "user-7423"]
CASES = [
    # persona, rng seed, from, to, target width, mode
    ("ha-1", 1, (260, 165), (150, 142), 44, "move"),
    ("ha-2", 2, (150, 142), (902, 613), 26, "move"),
    ("ha-3", 3, (902, 613), (515, 377), 34, "move"),
    ("ha-4", 4, (515, 377), (1040, 138), 56, "move"),
    ("ha-5", 5, (1040, 138), (198, 632), 24, "move"),
    ("ha-6", 6, (198, 632), (675, 205), 30, "move"),
    ("ha-1", 7, (300, 300), (330, 310), 24, "move"),      # short: no corrective submovement
    ("ha-2", 8, (300, 300), (300.8, 300.4), 24, "move"),  # negligible: one sample
    ("user-7423", 9, (10, 10), (1900, 1000), 8, "move"),  # long + small: the 1.7 s cap
    ("ha-3", 10, (62, 322), (427, 324), 24, "settle"),    # slider captcha
    ("ha-4", 11, (62, 322), (427, 324), 24, "held"),      # mouse.move with the button down
    ("ha-5", 12, (500, 200), (520, 260), 24, "settle"),   # short drag
]


def main():
    traits = []
    for pid in PERSONAS:
        t = shape_traits(make_persona(pid))
        traits.append({"persona": pid, "overshoot_rate": t.overshoot_rate, "curve": t.curve,
                       "drag_tempo": t.drag_tempo})
    paths = []
    found = {}
    for pid, seed, frm, to, w, mode in CASES:
        steps = plan_move(frm, to, make_persona(pid), target_w=w, settle=mode == "settle",
                          held=mode == "held", rng=mulberry32(seed))
        n = len(steps)
        idx = sorted({0, n // 4, n // 2, (3 * n) // 4, n - 1})
        paths.append({"persona": pid, "rng": seed, "from": list(frm), "to": list(to), "target_w": w,
                      "mode": mode, "n": n, "total_ms": sum(s[2] for s in steps),
                      "samples": [[i, steps[i][0], steps[i][1], steps[i][2]] for i in idx]})
        found[mode] = found.get(mode, 0) + 1
    doc = {
        "_about": ("Shared vectors for the humanize path planner: sdk/python/clearcote/_motion.py plan_move/"
                   "plan_drag/shape_traits, sdk/node/src/motion.ts and sdk/dotnet/src/Clearcote/Motion.cs must "
                   "plan these exact paths (abs tolerance 1e-6 px / ms; shape traits 1e-12) from "
                   "makePersona(persona) and mulberry32(rng). Generated by sdk/python/tests/gen_motion_vectors.py."),
        "shape_traits": traits,
        "paths": paths,
    }
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        json.dump(doc, f, indent=1)
        f.write("\n")
    print("wrote", OUT, found)


if __name__ == "__main__":
    main()
