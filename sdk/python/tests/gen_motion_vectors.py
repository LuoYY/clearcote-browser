# The wheel scroll-anchor model lane E unifies across the SDKs (PLAN.md lane E). On ceb7983 the three
# SDKs differ: Python x 0.5+-0.10 [0.12,0.88], y 0.34+-0.09 [0.10,0.62]; Node x 0.48+-0.10 [0.18,0.82],
# y 0.36+-0.09 [0.14,0.62]; .NET x 0.5+-0.12 [0.12,0.88], y 0.38+-0.10 [0.12,0.75]. The target is
# Python's. ``points`` are what a pure ``wheel_anchor_point(vw, vh, rng)`` (x = gauss_from(rng) first,
# then y) must return for mulberry32(seed); the SDK tests skip until that function exists.
ANCHOR = {"x": {"mean": 0.5, "sd": 0.10, "lo": 0.12, "hi": 0.88},
          "y": {"mean": 0.34, "sd": 0.09, "lo": 0.10, "hi": 0.62}, "target_w": 140}


def _anchor_point(vw, vh, rng):
    ax, ay = ANCHOR["x"], ANCHOR["y"]
    x = min(max(vw * ax["mean"] + gauss_from(rng) * vw * ax["sd"], vw * ax["lo"]), vw * ax["hi"])
    y = min(max(vh * ay["mean"] + gauss_from(rng) * vh * ay["sd"], vh * ay["lo"]), vh * ay["hi"])
    return x, y


def _pick(steps):
    n = len(steps)
    idx = sorted({0, n // 4, n // 2, (3 * n) // 4, n - 1})
    return n, sum(s[2] for s in steps), [[i, steps[i][0], steps[i][1], steps[i][2]] for i in idx]


def score_cases():
    """Synthetic traces every SDK's score_action must score identically (flags too)."""
    import random as _r
    rnd = _r.Random(232)
    straight = [{"x": 100 + i * 5, "y": 100, "t": i * 8} for i in range(60)]
    p1 = make_persona("ha-1")
    planned = _motionscore.steps_to_samples(plan_move((100, 100), (800, 500), p1, target_w=40, rng=mulberry32(5)))
    planned = [{"x": s["x"], "y": s["y"], "t": s["t"]} for s in planned]
    word = "the quick brown fox jumps over the lazy dog"
    robo_typed = [{"key": k, "down": i * 100.0, "up": i * 100.0 + 60} for i, k in enumerate(word)]
    t, human_typed = 0.0, []
    prev = None
    for k in word:
        fa, fb = _motionscore.finger_of(prev), _motionscore.finger_of(k)
        gap = max(30.0, rnd.gauss(150, 55)) * (1.4 if (fa and fb and fa == fb and fa[0] != 2) else 1.0)
        t += gap
        dwell = max(35.0, rnd.gauss(95, 22))
        human_typed.append({"key": k, "down": round(t, 3), "up": round(t + dwell, 3)})
        prev = k
    metronome = [{"t": i * 50.0, "dy": 120} for i in range(10)]
    t, notches = 0.0, []
    for b in (3, 4, 2, 3):
        for j in range(b):
            notches.append({"t": round(t, 3), "dy": 120})
            t += rnd.uniform(18, 55)
        t += rnd.uniform(120, 320)
    t, pad = 0.0, []
    v = 38.0
    while v >= 2:
        pad.append({"t": round(t, 3), "dy": round(v, 3), "mode": 0})
        t += rnd.uniform(9, 12)
        v *= 0.86
    sliced = [{"t": i * 40.0, "dy": d} for i, d in enumerate((39, 28, 20, 10, 3))]
    hover_none = [{"x": 300, "y": 200, "t": 0}]
    hover_ok = [{"x": 300 + rnd.gauss(0, 0.6), "y": 200 + rnd.gauss(0, 0.6), "t": i * 16.0} for i in range(25)]
    hover_ok[0] = {"x": 300, "y": 200, "t": 0}
    teleport_drag = ([{"x": 100 + i * 9, "y": 300, "t": i * 8.0, "buttons": 1} for i in range(40)]
                     + [{"x": 451, "y": 300, "t": 320.0, "buttons": 0}])
    good_drag = [{"x": 100, "y": 300, "t": 0, "buttons": 1}]
    t = 0.0
    for k in range(12):   # hesitation: the hand still (< 1 px) for ~190 ms after the press
        t += 16
        good_drag.append({"x": 100 + k * 0.05, "y": 300 + rnd.gauss(0, 0.15), "t": t, "buttons": 1})
    for x, y, sl in plan_drag((106, 300), (450, 302), p1, settle=True, rng=mulberry32(6)):
        t += sl
        good_drag.append({"x": x, "y": y, "t": t, "buttons": 1})
    good_drag.append({"x": good_drag[-1]["x"], "y": good_drag[-1]["y"], "t": t + 90, "buttons": 0})
    amb = _motionscore.steps_to_samples(plan_ambient((300, 300), VIEW, p1, 1500, rng=mulberry32(7)))
    amb = [{"x": s["x"], "y": s["y"], "t": s["t"]} for s in amb]
    cases = [("glide", "straight", straight), ("glide", "planned", planned), ("typed", "robot", robo_typed),
             ("typed", "human", human_typed), ("wheel", "metronome", metronome), ("wheel", "notch-bursts", notches),
             ("wheel", "trackpad", pad), ("wheel", "eased-slices", sliced), ("hover", "none", hover_none),
             ("hover", "dwell", hover_ok), ("drag", "teleport", teleport_drag), ("drag", "hesitant", good_drag),
             ("ambient", "planned", amb)]
    out = []
    for kind, name, samples in cases:
        # rounded BEFORE scoring: the stored samples are exactly what the other SDKs score
        samples = [{k: (round(v, 4) if isinstance(v, float) else v) for k, v in smp.items()} for smp in samples]
        r = _motionscore.score_action(kind, samples)
        out.append({"kind": kind, "name": name, "samples": samples, "score": r.score, "flags": r.flags})
    return out


def sc232_sections():
    drags, ambient, timings, anchors = [], [], [], []
    for pid, seed in SEEDS3:
        p = make_persona(pid)
        n, tot, smp = _pick(plan_drag((62, 322), (427, 324), p, settle=True, rng=mulberry32(seed)))
        drags.append({"persona": pid, "rng": seed, "from": [62, 322], "to": [427, 324], "settle": True,
                      "n": n, "total_ms": tot, "samples": smp})
        n, tot, smp = _pick(plan_ambient((300, 300), VIEW, p, 1500, rng=mulberry32(seed)))
        ambient.append({"persona": pid, "rng": seed, "from": [300, 300], "viewport": VIEW, "ms": 1500,
                        "n": n, "total_ms": tot, "samples": smp})
        r = mulberry32(seed)
        g, rel = drag_dwell(p, r)
        timings.append({"persona": pid, "rng": seed, "click_hold": click_hold(p, r), "key_dwell": key_dwell(p, r),
                        "grab_ms": g, "release_ms": rel, "rollover_rate": rollover_rate(p)})
        r = mulberry32(seed)
        anchors.append({"rng": seed, "viewport": [1180, 760], "points": [list(_anchor_point(1180, 760, r)) for _ in range(4)]})
    return {
        "drags": drags,
        "ambient": ambient,
        "timings": timings,
        "wheel_anchor": {"model": ANCHOR, "cases": anchors},
        "scores": score_cases(),
        "entry": entry_cases(),
        "entry_ambient": entry_ambient_cases(),
    }


# SC 239: a fresh page's first glide enters over the top edge (pro-r43-13's rule, lab row H 13). Every case runs
# the pipeline the SDKs run -- entry_point(target, view_w, rng) -> plan_move(from, target, ..., rng) ->
# enter_from_top(steps, from, rng), ONE rng in that order -- and pins the start, the kept sample count and the first,
# middle and last samples. ``view_w`` 0 = no readable viewport (the 1000 px default).
ENTRY_CASES = [
    # persona, rng, target, view_w, target_w
    ("ha-1", 41, (640, 380), 1180, 24),
    ("ha-2", 42, (60, 700), 1180, 24),
    ("ha-3", 43, (1120, 40), 1180, 36),
    ("ha-4", 44, (300, 12), 1366, 24),    # a target just under the top edge
    ("ha-5", 45, (900, 500), 0, 24),      # no viewport read: 1000 px default width
    ("ha-6", 46, (500, 200), 320, 24),    # a narrow view
]


def entry_cases():
    cases = []
    for pid, seed, target, vw, w in ENTRY_CASES:
        rng = mulberry32(seed)
        frm = entry_point(target, vw or None, rng)
        planned = plan_move(frm, target, make_persona(pid), target_w=w, rng=rng)
        steps = enter_from_top(planned, frm, rng)
        n = len(steps)
        idx = sorted({0, n // 2, n - 1})
        cases.append({"persona": pid, "rng": seed, "target": list(target), "view_w": vw, "target_w": w,
                      "from": [frm[0], frm[1]], "planned_n": len(planned), "n": n,
                      "samples": [[i, steps[i][0], steps[i][1], steps[i][2]] for i in idx]})
    return cases


# SC 239: an ambient drift on a fresh page comes in over the top edge INSIDE its budget -- entry_point(pos, view_w, rng)
# -> plan_ambient(start, view, persona, ms + ENTRY_LEAD_MS, rng) -> enter_from_top(plan, start, rng), one rng in that
# order (_humanize._ambient_plan; Node ambientPlan, .NET AmbientPlan).
ENTRY_AMBIENT_CASES = [
    # persona, rng, tracked pos, view (w, h), ms
    ("ha-1", 51, (260, 160), (1180, 760), 600),
    ("ha-2", 52, (140, 90), (1366, 768), 1200),
    ("ha-3", 53, (380, 240), (320, 640), 300),    # a narrow view; a short ask
]


def entry_ambient_cases():
    cases = []
    for pid, seed, pos, (vw, vh), ms in ENTRY_AMBIENT_CASES:
        rng = mulberry32(seed)
        start = entry_point(pos, vw, rng)
        planned = plan_ambient(start, {"width": vw, "height": vh}, make_persona(pid), ms + ENTRY_LEAD_MS, rng)
        steps = enter_from_top(planned, start, rng)
        n = len(steps)
        idx = sorted({0, 1, n // 2, n - 1})
        cases.append({"persona": pid, "rng": seed, "pos": list(pos), "view": [vw, vh], "ms": ms,
                      "start": [start[0], start[1]], "planned_n": len(planned), "n": n,
                      "total_ms": sum(s[2] for s in steps),
                      "samples": [[i, steps[i][0], steps[i][1], steps[i][2]] for i in idx]})
    return cases


