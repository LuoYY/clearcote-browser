"""Regenerate sdk/testdata/humanize_timing_vectors.json from the Python persona model.

usage: python tests/gen_timing_vectors.py   (from sdk/python)

Node (test/humanize-timing-aim.test.ts) and .NET (TimingAimTests.cs) read the same file: the persona's
timing traits, aim traits, the timing draws and the click points must agree across the three SDKs.
``persona_core`` pins the fields make_persona drew in 0.51.0 -- the new traits come from salted side
streams, so those must never move. Regenerate only together with the matching change in all three."""

import json
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from clearcote._motion import (  # noqa: E402
    aim_traits, click_hold, click_point, dblclick_gap, drag_dwell, key_dwell, make_persona, mulberry32,
    pause_ms, reset_aim_streams, timing_traits,
)

OUT = os.path.join(os.path.dirname(__file__), "..", "..", "testdata", "humanize_timing_vectors.json")
PERSONAS = ["ha-1", "ha-2", "ha-3", "ha-4", "ha-5", "ha-6", "user-7423"]
BOX = {"x": 100.0, "y": 100.0, "width": 160.0, "height": 40.0}
FROM = (20.0, 300.0)


def core(p):
    return [p.seed, p.device_hz, p.tremor_hz, p.tremor_amp, p.drift_amp, p.drift_tau, p.jitter, p.fitts_a,
            p.fitts_b, p.primary_frac, p.overshoot, p.max_corrections, p.approach_bias]


def main():
    rows, tim, aim, draws = [], [], [], []
    for k, pid in enumerate(PERSONAS):
        p = make_persona(pid)
        rows.append({"persona": pid, "core": core(p)})
        t = timing_traits(p)
        tim.append({"persona": pid, "click_hold_ms": t.click_hold_ms, "key_dwell_ms": t.key_dwell_ms,
                    "grab_ms": t.grab_ms, "release_ms": t.release_ms, "dblclick_gap_ms": t.dblclick_gap_ms,
                    "pause_scale": t.pause_scale, "typo_rate": t.typo_rate})
        a = aim_traits(p)
        aim.append({"persona": pid, "spread": a.spread, "undershoot": a.undershoot, "side_bias": a.side_bias})
        r = mulberry32(100 + k)
        g, rel = drag_dwell(p, r)
        d = {"persona": pid, "rng": 100 + k, "click_hold": click_hold(p, r), "key_dwell": key_dwell(p, r),
             "grab": g, "release": rel, "dblclick_gap": dblclick_gap(p, r), "pause_220_480": pause_ms(p, 220, 480, r),
             "click_point_rng": list(click_point(BOX, FROM, p, r))}
        # the identity's own aim stream from its start: the first three landing points
        reset_aim_streams()
        fresh = make_persona(pid)
        d["click_point_stream"] = [list(click_point(BOX, FROM, fresh)) for _ in range(3)]
        draws.append(d)
    doc = {
        "_about": ("Shared vectors for the per-persona timing and aim model: sdk/python/clearcote/_motion.py "
                   "timing_traits/aim_traits/click_hold/key_dwell/drag_dwell/dblclick_gap/pause_ms/click_point, "
                   "sdk/node/src/motion.ts and sdk/dotnet/src/Clearcote/Motion.cs must give these values "
                   "(abs tolerance 1e-9 ms / px) from makePersona(persona) and mulberry32(rng). draws are taken "
                   "in the listed order from ONE mulberry32(rng) stream; click_point_stream is a fresh persona's "
                   "own aim stream. box {x:100,y:100,width:160,height:40}, from (20,300). persona_core = the "
                   "fields 0.51.0 drew (seed, deviceHz, tremorHz, tremorAmp, driftAmp, driftTau, jitter, fittsA, "
                   "fittsB, primaryFrac, overshoot, maxCorrections, approachBias). Generated by "
                   "sdk/python/tests/gen_timing_vectors.py."),
        "box": BOX, "from": list(FROM),
        "persona_core": rows, "timing_traits": tim, "aim_traits": aim, "draws": draws,
    }
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        json.dump(doc, f, indent=1)
        f.write("\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
